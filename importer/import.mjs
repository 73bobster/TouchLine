// Favourite-teams importer: reads fixtures and finished results for chosen clubs from a pluggable source.
//
//   node importer/import.mjs [--source bbc|apifootball] [--teams rangers,heart-of-midlothian]
//        [--from YYYY-MM] [--to YYYY-MM] [--details none|recent|all] [--out importer/out/matches.json] [--sql importer/out/upsert.sql] [--force]
//
// Defaults: source bbc, both teams, last month through next month, --details recent, writes JSON only.
// --details: fetch each finished game's page for goals, assists, cards, line-ups and subs. 'recent' = games from the last 3 days
// (enough for an hourly poll, with a window to catch late corrections); 'all' = every finished game (use for a first backfill).
// Polling rule: only runs between 13:00 and 23:59 UK time (override with --force). Run it hourly at most.
// It never writes to the database itself: --sql produces an upsert for db/migrations/002_pro_matches.sql
// that you (or a workflow holding a Neon secret) can run.
import fs from 'node:fs';
import path from 'node:path';

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => {
  if (a.startsWith('--')) acc.push([a.slice(2), all[i + 1] && !all[i + 1].startsWith('--') ? all[i + 1] : true]);
  return acc;
}, []));

const say = (s = '') => console.log(s);
const summary = [];
const note = (s = '') => { summary.push(s); say(s); };

export function ukHour(now = new Date()) {
  return +new Intl.DateTimeFormat('en-GB', { timeZone: 'Europe/London', hour: '2-digit', hourCycle: 'h23' }).format(now);
}
export const inPollWindow = (now = new Date()) => ukHour(now) >= 13; // 13:00 to 23:59

export function monthRange(from, to) {
  const out = [];
  let [y, m] = from.split('-').map(Number);
  const [ey, em] = to.split('-').map(Number);
  while (y * 12 + m <= ey * 12 + em) { out.push(`${y}-${String(m).padStart(2, '0')}`); m++; if (m > 12) { m = 1; y++; } }
  return out;
}

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

export function toSql(rows, source) {
  const lines = ['-- Generated by importer/import.mjs. Safe to re-run: upserts on (source, source_ref); detail rows are replaced per match.', 'begin;'];
  const arr = (a) => `array[${(a || []).join(',')}]::int[]`;
  for (const r of rows) {
    lines.push(
      `insert into public.pro_matches (source, source_ref, teams, comp, match_date, kickoff, home, away, home_goals, away_goals, status, raw_status, page_id) values (` +
      `${q(source)}, ${q(r.ref)}, array[${r.teams.map(q).join(',')}], ${q(r.comp)}, ${q(r.date)}, ${q(r.kickoff)}, ${q(r.home)}, ${q(r.away)}, ` +
      `${r.homeGoals ?? 'null'}, ${r.awayGoals ?? 'null'}, ${q(r.status)}, ${q(r.rawStatus)}, ${q(r.pageId)}) ` +
      `on conflict (source, source_ref) do update set teams = excluded.teams, comp = excluded.comp, kickoff = coalesce(excluded.kickoff, public.pro_matches.kickoff), ` +
      `home_goals = excluded.home_goals, away_goals = excluded.away_goals, status = excluded.status, raw_status = excluded.raw_status, page_id = coalesce(excluded.page_id, public.pro_matches.page_id), updated_at = now();`);
    const d = r.detail;
    if (!d) continue;
    const where = `source = ${q(source)} and source_ref = ${q(r.ref)}`;
    const side = (n) => d.sides.find((s) => s.side === n) || {};
    lines.push(
      `update public.pro_matches set venue = ${q(d.venue)}, attendance = ${d.attendance ?? 'null'}, referee = ${q(d.referee)}, ` +
      `home_manager = ${q(side('home').manager)}, away_manager = ${q(side('away').manager)}, home_formation = ${q(side('home').formation)}, away_formation = ${q(side('away').formation)}, ` +
      `detail_fetched_at = now() where ${where};`,
      `delete from public.pro_match_players where ${where};`,
      `delete from public.pro_match_events where ${where};`);
    for (const s of d.sides) {
      for (const p of s.players) {
        lines.push(
          `insert into public.pro_match_players (source, source_ref, side, num, name, surname, pos, starter, captain, on_min, off_min, replaced_by, replaced, yellow, red) values (` +
          `${q(source)}, ${q(r.ref)}, ${q(s.side)}, ${p.num}, ${q(p.name)}, ${q(p.surname)}, ${q(p.pos)}, ${p.starter}, ${p.captain}, ${p.onMin ?? 'null'}, ${p.offMin ?? 'null'}, ` +
          `${q(p.replacedBy)}, ${q(p.replaced)}, ${arr(p.yellow)}, ${arr(p.red)}) on conflict (source, source_ref, side, num) do nothing;`);
      }
    }
    d.events.forEach((e, i) => lines.push(
      `insert into public.pro_match_events (source, source_ref, seq, type, side, minute, player, assist, on_player, detail) values (` +
      `${q(source)}, ${q(r.ref)}, ${i + 1}, ${q(e.type)}, ${q(e.side)}, ${e.minute}, ${q(e.player)}, ${q(e.assist)}, ${q(e.on)}, ${q(e.detail)});`));
  }
  lines.push('commit;');
  return lines.join('\n') + '\n';
}

// A game appears on both clubs' pages when they play each other: merge into one row.
export function merge(matches) {
  const byRef = new Map();
  for (const m of matches) {
    const ref = `${m.date}|${m.home}|${m.away}`;
    const cur = byRef.get(ref);
    if (cur) { if (!cur.teams.includes(m.team)) cur.teams.push(m.team); if (!cur.comp && m.comp) cur.comp = m.comp; if (!cur.pageId && m.pageId) cur.pageId = m.pageId; continue; }
    byRef.set(ref, { ...m, ref, teams: [m.team] });
  }
  return [...byRef.values()].sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));
}


// Fetch goals, assists, cards, line-ups and subs for finished games (needs a <source>-detail.mjs module).
async function addDetails(rows, sourceId, mode) {
  if (mode === 'none') return;
  const mod = await import(`./sources/${sourceId}-detail.mjs`).catch(() => null);
  if (!mod) { note(`(no match detail available from source "${sourceId}")`); return; }
  const cutoff = new Date(Date.now() - 3 * 86400e3).toISOString().slice(0, 10);
  const todo = rows.filter((r) => r.status === 'finished' && r.pageId && (mode === 'all' || r.date >= cutoff));
  let ok = 0;
  for (const r of todo) {
    try {
      r.detail = await mod.fetchMatchPage(r.pageId);
      ok++;
      r.detail.notes.forEach((n) => note(`! ${r.date} ${r.home} v ${r.away}: ${n}`));
    } catch (e) { note(`! ${r.date} ${r.home} v ${r.away}: ${e.message}`); }
    await new Promise((res) => setTimeout(res, 1500));
  }
  const missing = rows.filter((r) => r.status === 'finished' && !r.pageId).length;
  note(`match detail: ${ok}/${todo.length} fetched${missing ? `, ${missing} finished game(s) had no match page link` : ''}`);
  const cov = (f) => rows.filter((r) => r.detail && f(r.detail)).length;
  todo.filter((r) => r.detail).slice(-2).forEach((r) => {
    const d = r.detail;
    note(`\nsample: ${r.date} ${r.home} ${r.homeGoals}-${r.awayGoals} ${r.away} (${d.venue || '?'}, att ${d.attendance ?? '?'}, ref ${d.referee || '?'})`);
    d.sides.forEach((s) => note(`  ${s.side} ${s.club}: ${s.formation || '?'}, manager ${s.manager || '?'}, starters ${s.players.filter((p) => p.starter).length}, bench ${s.players.filter((p) => !p.starter).length}`));
    d.events.forEach((e) => note(`  ${String(e.minute).padStart(2)}' ${e.side} ${e.type}: ${e.player}${e.assist ? ' (assist ' + e.assist + ')' : ''}${e.on ? ' -> ' + e.on : ''}${e.detail ? ' [' + e.detail + ']' : ''}`));
  });
  note(`  with line-ups: ${cov((d) => d.sides.some((s) => s.players.length))}, with goals: ${cov((d) => d.events.some((e) => /goal/.test(e.type)))}, with cards: ${cov((d) => d.events.some((e) => /yellow|red/.test(e.type)))}, with subs: ${cov((d) => d.events.some((e) => e.type === 'sub'))}`);
}

async function main() {
  if (!args.force && !inPollWindow()) {
    note(`Outside the polling window (13:00 to 23:59 UK time; it is ${ukHour()}:xx now). Nothing fetched. Use --force to override.`);
    return;
  }
  const sourceId = args.source || 'bbc';
  const source = await import(`./sources/${sourceId}.mjs`);
  const given = String(args.teams || process.env.FOLLOWED_TEAMS || '').split(',').map((s) => s.trim()).filter(Boolean);
  const teams = given.length ? [...new Set(given)] : ['rangers', 'heart-of-midlothian'];
  const now = new Date();
  const ym = (d) => `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}`;
  const from = args.from || ym(new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() - 1, 1)));
  const to = args.to || ym(new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + 1, 1)));
  const months = monthRange(from, to);

  note(`# Favourite teams import (${source.id})`);
  note(`teams: ${teams.join(', ')}; months: ${months.join(', ')}`);
  const all = [];
  for (const team of teams) {
    let list;
    try { list = await source.listMatches({ team, months }); } catch (e) { note(`${team}: skipped (${e.message})`); continue; }
    note(`${team}: ${list.length} match(es), ${list.filter((m) => m.status === 'finished').length} finished`);
    all.push(...list);
  }
  const rows = merge(all);
  await addDetails(rows, sourceId, String(args.details || 'recent'));
  const odd = rows.filter((r) => r.status === 'other' || r.status === 'live');
  note(`\n${rows.length} unique match(es) after merging; ${rows.filter((r) => r.status === 'finished').length} finished, ${rows.filter((r) => r.status === 'scheduled').length} scheduled${odd.length ? `, ${odd.length} live/other` : ''}`);
  odd.forEach((r) => note(`? ${r.date} ${r.home} ${r.homeGoals ?? '-'}-${r.awayGoals ?? '-'} ${r.away} [status text: "${r.rawStatus}"]`));
  rows.slice(-8).forEach((r) => note(`- ${r.date} ${r.comp || '?'}: ${r.home} ${r.homeGoals ?? '-'}-${r.awayGoals ?? '-'} ${r.away} [${r.rawStatus}]`));

  const outFile = args.out || 'importer/out/matches.json';
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, JSON.stringify({ source: source.id, fetchedAt: now.toISOString(), matches: rows }, null, 2));
  if (args.sql) {
    fs.mkdirSync(path.dirname(args.sql), { recursive: true });
    fs.writeFileSync(args.sql, toSql(rows, source.id));
    note(`wrote ${args.sql}`);
  }
  if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, '```\n' + summary.join('\n') + '\n```\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => { console.error(e.message); process.exit(1); });
}
